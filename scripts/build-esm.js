#!/usr/bin/env node
// Writes make-model-dropdown.mjs, the ES module build, from the one source:
// make-model-dropdown.js (UMD: <script> tags, require(), bundlers).
//
// Not a bundler: it swaps the UMD wrapper for `const VehiclesDropdown = …`
// plus `export` lines, byte for byte otherwise. The ES module exists because
// browsers, Rails importmap and jspm cannot import a UMD file, and it must be
// ONE self-contained file: `bin/importmap pin` vendors a single file and
// never follows its relative imports.
//
//   node scripts/build-esm.js          # write make-model-dropdown.mjs
//   node scripts/build-esm.js --check  # exit 1 if it is out of date (CI, prepublish)
"use strict"

const fs = require("node:fs")
const path = require("node:path")

const ROOT = path.join(__dirname, "..")
const SOURCE = path.join(ROOT, "make-model-dropdown.js")
const TARGET = path.join(ROOT, "make-model-dropdown.mjs")

const HEADER = `(function (root, factory) {
  if (typeof module === "object" && module.exports) module.exports = factory()
  else root.VehiclesDropdown = factory()
})(globalThis, function () {
`
const FOOTER = "})\n"

function build() {
  const source = fs.readFileSync(SOURCE, "utf8")
  const start = source.indexOf(HEADER)
  if (start < 0 || !source.endsWith(FOOTER)) {
    throw new Error("build-esm: the UMD wrapper in make-model-dropdown.js changed; update scripts/build-esm.js")
  }
  return source.slice(0, start) +
    "// GENERATED by scripts/build-esm.js from make-model-dropdown.js. Do not edit.\n" +
    "const VehiclesDropdown = (function () {\n" +
    source.slice(start + HEADER.length, source.length - FOOTER.length) +
    "})()\n\n" +
    "export default VehiclesDropdown\n" +
    "export const { attach, norm, findMake, findModel, version } = VehiclesDropdown\n"
}

if (require.main === module) {
  const output = build()
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, "utf8") : ""
    if (current !== output) {
      console.error("make-model-dropdown.mjs is out of date: run `node scripts/build-esm.js`")
      process.exit(1)
    }
  } else {
    fs.writeFileSync(TARGET, output)
  }
}

module.exports = { build }
